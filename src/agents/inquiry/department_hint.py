# src/agents/inquiry/department_hint.py
#
# 症状 → 科室的确定性兜底。
#
# 为什么不只靠图谱：问诊收敛到低置信度时（图谱里大量疾病本体残缺，
# 单症状命中只有 0.4 左右），原逻辑把科室一律写成"综合内科"。
# 实测"身上起红疹很痒该挂哪个科"追问两轮后给出"综合内科"，
# 而图谱的 Department 里本来就有"皮肤科"；"眼痛/流泪/畏光"同理应到"眼科"。
# 这层兜底只在低置信度时使用，不覆盖图谱给出的明确科室。

from __future__ import annotations

# 顺序有意义：越靠前越特异，先匹配先返回
SYMPTOM_DEPT_HINTS: tuple[tuple[tuple[str, ...], str], ...] = (
    (("红疹", "丘疹", "鳞屑", "皮疹", "瘙痒", "很痒", "水疱", "脱屑",
      "荨麻疹", "湿疹", "痘", "斑块", "皮肤"), "皮肤科"),
    (("眼痛", "流泪", "畏光", "眼红", "视物模糊", "眼睛干", "眼皮", "黑眼球"), "眼科"),
    (("牙痛", "牙龈", "口腔溃疡", "智齿", "蛀牙"), "口腔科"),
    (("耳鸣", "耳痛", "听力下降", "耳朵", "鼻塞", "流鼻血", "咽喉痛", "嗓子"), "耳鼻喉科"),
    (("尿频", "尿急", "尿痛", "血尿", "排尿困难"), "泌尿外科"),
    (("月经", "白带", "痛经", "阴道"), "妇科"),
    (("怀孕", "孕期", "孕早", "孕晚", "胎动"), "产科"),
    (("孩子", "宝宝", "婴儿", "小儿", "儿童"), "儿科"),
)


def hint_department(text: str) -> str:
    """按症状文本给一个科室建议；匹配不到返回空串（由调用方决定默认值）。"""
    text = text or ""
    for keywords, dept in SYMPTOM_DEPT_HINTS:
        if any(k in text for k in keywords):
            return dept
    return ""
